#!/usr/bin/env python3
"""Lists every OpenGL ES 2.0-3.2 core command from Khronos gl.xml as
P(version, name) lines: what Dawn's generated loader (LoadOpenGLESProcs)
asks its getProc for on an ES 3.2 context.
  gen-procs.py path/to/gl.xml > src/es32_procs.inc"""
import sys
import xml.etree.ElementTree as ET

root = ET.parse(sys.argv[1]).getroot()
print("/* Generated by gen-procs.py from Khronos gl.xml: OpenGL ES 2.0-3.2 core commands. */")
total = 0
for feature in root.findall("feature"):
    if feature.get("api") != "gles2":
        continue
    version = feature.get("number").replace(".", "")
    for require in feature.findall("require"):
        for command in require.findall("command"):
            print(f'P({version}, "{command.get("name")}")')
            total += 1
print(f"/* {total} commands */")
