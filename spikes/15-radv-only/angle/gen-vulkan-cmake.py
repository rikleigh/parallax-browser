#!/usr/bin/env python3
"""Write Vulkan.cmake for ANGLE from renderer/vulkan/vulkan_backend.gni.

ANGLE's own gni-to-cmake.py needs `ply`; this file's lists are plain, so a
regex reads them. Only the lists the PS5 title needs: the backend sources,
and the Linux display sources (DisplayVkSimple for VK_KHR_display,
offscreen, headless). The internal shaders are .inc files that
vk_internal_shaders_autogen.cpp includes, so they need no list.

    gen-vulkan-cmake.py <ANGLE source tree> <output Vulkan.cmake>
"""
import re
import sys
from pathlib import Path

root = Path(sys.argv[1])
out = Path(sys.argv[2])
vk = "src/libANGLE/renderer/vulkan/"


def gni_list(path: Path, name: str, op: str = "="):
    text = path.read_text()
    m = re.search(r"^\s*" + re.escape(name) + r"\s*" + re.escape(op) + r"\s*\[(.*?)\]",
                  text, re.S | re.M)
    if not m:
        sys.exit(f"{path}: no list {name} {op}")
    return re.findall(r'"([^"]+)"', m.group(1))


backend = root / vk / "vulkan_backend.gni"
lists = {
    "vulkan_backend_sources": gni_list(backend, "vulkan_backend_sources"),
    "vulkan_backend_dma_buf_sources": gni_list(backend, "vulkan_backend_dma_buf_sources"),
}

with out.open("w") as f:
    f.write(f"# Generated by spikes/15-radv-only/angle/gen-vulkan-cmake.py from\n"
            f"# {vk}vulkan_backend.gni. Do not edit.\n\n")
    for name, items in lists.items():
        f.write(f"set({name}\n")
        for item in items:
            f.write(f'    "{vk}{item}"\n')
        f.write(")\n\n")
print(f"{out}: " + ", ".join(f"{k} {len(v)}" for k, v in lists.items()))
